// The settings repository stages only the ingestion contract (ingestion-contract/build/contracts-repo), so the
// canonical document is unpacked here, with the `../service-runtime/` files its $ref points at beside it, and handed to
// the plugin's prepare task as its source. Nothing of the contract is copied into the repository.
val stageCanonicalContract by tasks.registering(Sync::class) {
    from(zipTree(contractsBundle.singleFile)) {
        include("canonical/openapi.yaml", "service-runtime/**")
    }
    into(layout.buildDirectory.dir("canonical-contract"))
}
tasks.named<gst.build.contracts.PrepareDecimalSpecTask>("prepareContractClientSpec") {
    source.set(stageCanonicalContract.map { layout.buildDirectory.file("canonical-contract/canonical/openapi.yaml").get() })
}

