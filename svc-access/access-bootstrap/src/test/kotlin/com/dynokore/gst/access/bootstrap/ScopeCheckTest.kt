package com.dynokore.gst.access.bootstrap

import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import java.io.File

/**
 * The scope check of INV-T-8850 (INV-Q-9323 A), as a deny-by-default function over the lines of
 * `git diff --name-only origin/main` and the two generated-file diffs. Paths match by equality or by the four module
 * prefixes only; anything else is a finding.
 */
class ScopeCheckTest {
    private val exact =
        setOf(
            "gradle/libs.versions.toml",
            "gradle/verification-metadata.xml",
            "access-contract/gradle.lockfile",
            "operations.tsv",
            "ac-keys.tsv",
        )
    private val prefixes = listOf("access-domain/", "access-application/", "access-adapters/", "access-bootstrap/")

    private fun pathFindings(paths: List<String>): List<String> =
        paths.filter { it !in exact && prefixes.none { prefix -> it.startsWith(prefix) } }

    private fun contentLines(
        diff: List<String>,
        sign: Char,
    ): List<String> = diff.filter { it.startsWith(sign) && !it.startsWith("$sign$sign$sign") }.map { it.substring(1) }

    private fun lockFindings(
        diff: List<String>,
        pinSuffix: String,
    ): List<String> {
        val removed = contentLines(diff, '-')
        val added = contentLines(diff, '+')
        val expected = "platform-contracts-bundle:platform-contracts:0.0.0-dev+$pinSuffix=contractsBundle"
        return buildList {
            if (removed.size != 1 || added.size != 1) add("not exactly one removed and one added line")
            if (added.singleOrNull() != expected) add("added line is not $expected")
        }
    }

    private val generated =
        listOf(
            Regex("""\s*<component .*>"""),
            Regex("""\s*</component>"""),
            Regex("""\s*<artifact .*>"""),
            Regex("""\s*</artifact>"""),
            Regex("""\s*<sha256 value="[0-9a-f]+" origin="Generated by Gradle"/>"""),
        )

    private fun metadataFindings(diff: List<String>): List<String> =
        buildList {
            contentLines(diff, '-').forEach { add("removed: $it") }
            contentLines(diff, '+').filter { line -> generated.none { it.matches(line) } }.forEach { add("added: $it") }
        }

    @Test
    fun `INV-AC-8848 the path check admits the allowed set and reports every look-alike`() {
        val allowed =
            exact.toList() +
                listOf(
                    "access-domain/x",
                    "access-application/x",
                    "access-adapters/x",
                    "access-bootstrap/src/y",
                )
        assertThat(pathFindings(allowed)).isEmpty()
        val lookAlikes =
            listOf(
                "access-contract/src/main/x",
                "access-bootstraps/x",
                "gateway-authz/x",
                ".gitlab-ci.yml",
                "libs.versions.toml",
                "access-contract/gradle.lockfile.bak",
                "gradle/verification-metadata.xml.orig",
                "verification-metadata.xml",
                "gradle/settings-gradle.lockfile",
                "settings-gradle.lockfile",
            )
        lookAlikes.forEach { assertThat(pathFindings(listOf(it))).describedAs(it).containsExactly(it) }
    }

    @Test
    fun `INV-AC-8848 the lock file diff holds one changed line equal to the pin and each probe fails`() {
        val pin = "21fc1bf0"
        val line = "platform-contracts-bundle:platform-contracts:0.0.0-dev+"
        val good = listOf("-${line}d6f0aac8=contractsBundle", "+$line$pin=contractsBundle")
        assertThat(lockFindings(good, pin)).isEmpty()
        // probes: a second changed line; a suffix that differs from the pin
        assertThat(lockFindings(good + "+extra:lib:1=x", pin)).isNotEmpty()
        assertThat(lockFindings(good + "-extra:lib:1=x", pin)).isNotEmpty()
        assertThat(lockFindings(listOf(good[0], "+${line}deadbeef=contractsBundle"), pin)).isNotEmpty()
        assertThat(lockFindings(emptyList(), pin)).isNotEmpty()
        // the committed lock file carries the pin
        val toml = File("../gradle/libs.versions.toml").readText()
        val suffix = Regex("""(?m)^platformContractsBundle\s*=\s*"0\.0\.0-dev\+([^"]*)"""").find(toml)!!.groupValues[1]
        assertThat(File("../access-contract/gradle.lockfile").readLines()).contains("$line$suffix=contractsBundle")
    }

    @Test
    fun `INV-AC-8848 the verification metadata diff holds only Gradle-generated additions and each probe fails`() {
        val sha = """<sha256 value="ab12" origin="Generated by Gradle"/>"""
        val good =
            listOf(
                "+<component group=\"g\" name=\"n\" version=\"1\">",
                "+<artifact name=\"n-1.jar\">",
                "+$sha",
                "+</artifact>",
                "+</component>",
            )
        assertThat(metadataFindings(good)).isEmpty()
        // probes: a removed line; trusted-artifacts; ignored-keys; a manual sha256
        assertThat(metadataFindings(good + "-<component group=\"g\">")).isNotEmpty()
        assertThat(metadataFindings(good + "+<trusted-artifacts>")).isNotEmpty()
        assertThat(metadataFindings(good + "+<ignored-keys>")).isNotEmpty()
        assertThat(metadataFindings(good + """+<sha256 value="ab12" origin="Manual"/>""")).isNotEmpty()
    }
}
