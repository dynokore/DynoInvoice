package gst.catalogue

import java.io.File

/**
 * Emits `RolePermission.kt` (INV-T-7987; STK-61, INV-Q-7979 A): the `RolePermissions` object that serves the checked
 * role-by-permission table of INV-NOTE-3 sections 22.2 and 22.3. Generated into the package of `VariationPoint.kt`, whose
 * `DeploymentForm` it uses. A cell that is not listed is absent (DENIED).
 */
object RolePermissionKotlinEmitter {
    fun emit(
        packageName: String,
        table: RolePermissionTable,
        machine: List<MachinePermissionRow> = emptyList(),
    ): String =
        buildString {
            appendLine("// GENERATED — do not edit by hand.")
            appendLine("//")
            appendLine("// Generated by catalogue/generator (INV-T-7987) from catalogue/role-permissions/role-permissions.yaml,")
            appendLine("// the hand-kept transcription of INV-NOTE-3 sections 22.2 and 22.3 and INV-REQ-999.")
            appendLine()
            appendLine("package $packageName")
            appendLine()
            appendLine("/** What a permission cell allows: the published Y (PERMITTED) or S (WITHIN_SCOPE). */")
            appendLine("enum class RoleAllowance {")
            RoleAllowance.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/** Whether a permission reads or changes state. */")
            appendLine("enum class PermissionKind {")
            PermissionKind.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/** The role-by-permission table (INV-NOTE-3 sections 22.2 and 22.3). A cell that is not listed is DENIED. */")
            appendLine("object RolePermissions {")
            appendLine("    private val roleForms: Map<String, Set<DeploymentForm>> =")
            appendLine("        mapOf(")
            table.roles.forEach { r ->
                appendLine("            ${lit(r.key)} to setOf(${r.forms.joinToString { "DeploymentForm.$it" }}),")
            }
            appendLine("        )")
            appendLine()
            appendLine("    private val permissionKinds: Map<String, PermissionKind> =")
            appendLine("        mapOf(")
            table.permissions.forEach { appendLine("            ${lit(it.key)} to PermissionKind.${it.kind},") }
            appendLine("        )")
            appendLine()
            appendLine("    private val cellsByForm: Map<DeploymentForm, Map<String, Map<String, RoleAllowance>>> =")
            appendLine("        mapOf(")
            DeploymentForm.entries.forEach { form ->
                appendLine("            DeploymentForm.$form to")
                appendLine("                mapOf(")
                table.roles.filter { form in it.forms }.forEach { role ->
                    val cells = table.permissions.mapNotNull { p -> p.cells.singleOrNull { it.role == role.key && it.form == form }?.let { p.key to it } }
                    if (cells.isEmpty()) {
                        appendLine("                    ${lit(role.key)} to emptyMap(),")
                    } else {
                        appendLine("                    ${lit(role.key)} to")
                        appendLine("                        mapOf(")
                        cells.forEach { (key, cell) -> appendLine("                            ${lit(key)} to RoleAllowance.${cell.allowance},") }
                        appendLine("                        ),")
                    }
                }
                appendLine("                ),")
            }
            appendLine("        )")
            appendLine()
            appendLine("    /** The roles that exist in [form]. */")
            appendLine("    fun roles(form: DeploymentForm): Set<String> = roleForms.filterValues { form in it }.keys")
            appendLine()
            appendLine("    /** The listed cells of [form]: role key, then permission key. A cell that is not listed is DENIED. */")
            appendLine("    fun cells(form: DeploymentForm): Map<String, Map<String, RoleAllowance>> = cellsByForm.getValue(form)")
            appendLine()
            appendLine("    /** The kind of [permissionKey], or null for a key that is not in the table. */")
            appendLine("    fun kind(permissionKey: String): PermissionKind? = permissionKinds[permissionKey]")
            appendLine("}")
            appendLine()
            appendLine("/**")
            appendLine(" * The operation-to-roles map (INV-T-10641, INV-NOTE-10639 R3): per deployment form, the roles with a cell on a permission")
            appendLine(" * key. Generated as a literal from the same table in the same run as [RolePermissions]; a key without a cell is absent.")
            appendLine(" */")
            appendLine("object OperationRoles {")
            appendLine("    private val rolesByForm: Map<DeploymentForm, Map<String, Map<String, RoleAllowance>>> =")
            appendLine("        mapOf(")
            DeploymentForm.entries.forEach { form ->
                appendLine("            DeploymentForm.$form to")
                appendLine("                mapOf(")
                table.permissions.forEach { p ->
                    val cells = p.cells.filter { it.form == form }
                    if (cells.isNotEmpty()) {
                        appendLine("                    ${lit(p.key)} to")
                        appendLine("                        mapOf(")
                        cells.forEach { appendLine("                            ${lit(it.role)} to RoleAllowance.${it.allowance},") }
                        appendLine("                        ),")
                    }
                }
                machineKeys(machine).forEach { (key, roles) ->
                    appendLine("                    ${lit(key)} to")
                    appendLine("                        mapOf(")
                    roles.forEach { appendLine("                            ${lit(it)} to RoleAllowance.PERMITTED,") }
                    appendLine("                        ),")
                }
                appendLine("                ),")
            }
            appendLine("        )")
            appendLine()
            appendLine("    /** The roles with a cell on [permissionKey] in [form], with the cell's allowance; empty for a key with no cell there. */")
            appendLine("    fun rolesFor(form: DeploymentForm, permissionKey: String): Map<String, RoleAllowance> =")
            appendLine("        rolesByForm.getValue(form)[permissionKey] ?: emptyMap()")
            appendLine()
            appendLine("    /** The permission keys that have at least one cell in [form]. */")
            appendLine("    fun keys(form: DeploymentForm): Set<String> = rolesByForm.getValue(form).keys")
            appendLine("}")
        }

    /** Machine key (`machine.` + permission) to its machine roles, in file order; the same in every form. */
    private fun machineKeys(machine: List<MachinePermissionRow>): List<Pair<String, List<String>>> =
        machine.groupBy({ MachinePermissions.PREFIX + it.permission }, { MachinePermissions.roleOf(it.principalType) }).toList()

    private fun lit(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
}

/** One data row of `access/schemas/machine-principal-permissions.tsv`, exactly as written (no trimming). */
data class MachinePermissionRow(
    val principalType: String,
    val permission: String,
)

/**
 * The machine section of `OperationRoles` (INV-T-13568, INV-REQ-584, owner answer INV-Q-10649 C). The tsv is the only place
 * the (type, permission) pairs are written; the generator derives the role `machine.<name>` and the key `machine.<permission>`.
 */
object MachinePermissions {
    const val PREFIX = "machine."

    /** The six principal types of INV-REQ-584 behavior 1; a seventh is a build failure. */
    val types: List<String> = listOf("INGEST", "FILING_WORKFLOW", "AP_CALLBACK", "REPORTING", "MONITORING", "CERTIFICATION")

    /** `FILING_WORKFLOW` to `machine.filing-workflow`. */
    fun roleOf(principalType: String): String = PREFIX + principalType.lowercase().replace('_', '-')

    private const val HEADER = "principalType\tpermission\tsource"

    /** Reads the tsv strictly: blank and `#` lines are skipped, the header must match, every data row has three columns. */
    fun parse(file: File): List<MachinePermissionRow> {
        val lines = file.readLines().filter { it.isNotBlank() && !it.startsWith("#") }
        require(lines.isNotEmpty() && lines.first() == HEADER) { "${file.name}: the header must be exactly '$HEADER'." }
        return lines.drop(1).mapIndexed { i, line ->
            val cols = line.split('\t')
            require(cols.size == 3) { "${file.name}: data row ${i + 1} has ${cols.size} columns, not 3." }
            MachinePermissionRow(cols[0], cols[1])
        }
    }
}
