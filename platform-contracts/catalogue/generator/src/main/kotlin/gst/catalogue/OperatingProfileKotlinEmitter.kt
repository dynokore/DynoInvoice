package gst.catalogue

/**
 * Emits `OperatingProfile.kt` (INV-T-3277; STK-61, INV-Q-3233): one `OperatingProfile`
 * entry per vendored PRF row, named after its id (`PRF_1` .. `PRF_7`), each value a typed
 * reference to a `VariationPoint` entry and its option keys. Generated into the same
 * package as `VariationPoint.kt`, whose `VariationPoint`, `VpStatus` and `ValueType` it
 * references, so a reference to a missing row cannot even compile.
 *
 * `previousVersion` and `previousValues` come from the previous vendored snapshot (null
 * on the first); `OperatingProfiles.differences` is the per-profile difference shown when
 * an update is offered (INV-REQ-1245 b4, INV-AC-2231), the same rule
 * [ProfileVersionChecker.differences] applies at generation time.
 */
object OperatingProfileKotlinEmitter {
    fun emit(
        packageName: String,
        profiles: List<ParsedOperatingProfile>,
        previous: List<ParsedOperatingProfile>?,
    ): String =
        buildString {
            val prev = previous?.associateBy { it.id }
            appendLine("// GENERATED — do not edit by hand.")
            appendLine("//")
            appendLine("// Generated by catalogue/generator (INV-T-3277) from")
            appendLine("// catalogue/operating-profiles/operating-profiles.yaml, itself vendored from the Keel")
            appendLine("// INV operating-profile rows PRF-1..PRF-7 (INV-REQ-1252..1258) — see that file's header.")
            appendLine()
            appendLine("package $packageName")
            appendLine()
            appendLine("/** A profile's status (INV-REQ-1249: available only with its certification set). */")
            appendLine("enum class ProfileStatus {")
            ProfileStatus.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/**")
            appendLine(" * A typed value a profile sets within its option's bounds (INV-Q-2934): a scalar carries [value]; a record")
            appendLine(" * carries only the [fields] it sets (a field it omits keeps the option's default, INV-Q-3320).")
            appendLine(" */")
            appendLine("data class ProfileTypedValue(")
            appendLine("    val type: ValueType,")
            appendLine("    val unit: String?,")
            appendLine("    val value: java.math.BigDecimal?,")
            appendLine("    val fields: Map<String, ProfileTypedValue> = emptyMap(),")
            appendLine(")")
            appendLine()
            appendLine("/** A value Keel has not typed yet: its reason and the open question that holds it. Never applied. */")
            appendLine("data class UnresolvedValue(")
            appendLine("    val reason: String,")
            appendLine("    val pendingQuestion: String,")
            appendLine(")")
            appendLine()
            appendLine("/**")
            appendLine(" * One value of a profile (INV-Q-3285 A): the option key(s) of [variationPoint] it sets —")
            appendLine(" * [option] on a single-select row, [options] on a multi-select one — and what the row's")
            appendLine(" * text adds: [condition] answered at apply with [otherwiseOption] when it does not hold,")
            appendLine(" * [alternatives] chosen by [alternativeBy], [adds] list entries, [atApply] the datum the")
            appendLine(" * applier supplies, [explicitDefault], and [needsAcknowledgement] (LOOSER options that need")
            appendLine(" * acknowledgeControlRelaxation, INV-REQ-1244). [unresolved] is set, and no option is, for a")
            appendLine(" * value Keel has not typed. [text] is the row's own words, not part of the value.")
            appendLine(" */")
            appendLine("data class ProfileValue(")
            appendLine("    val variationPoint: VariationPoint,")
            appendLine("    val requirement: String,")
            appendLine("    val text: String,")
            appendLine("    val option: String? = null,")
            appendLine("    val options: List<String> = emptyList(),")
            appendLine("    val typedValue: ProfileTypedValue? = null,")
            appendLine("    val condition: String? = null,")
            appendLine("    val recommended: Boolean = false,")
            appendLine("    val otherwiseOption: String? = null,")
            appendLine("    val alternatives: List<String> = emptyList(),")
            appendLine("    val alternativeBy: String? = null,")
            appendLine("    val adds: List<String> = emptyList(),")
            appendLine("    val atApply: String? = null,")
            appendLine("    val explicitDefault: Boolean = false,")
            appendLine("    val needsAcknowledgement: List<String> = emptyList(),")
            appendLine("    val unresolved: UnresolvedValue? = null,")
            appendLine(") {")
            appendLine("    /** INV-REQ-1251: a planned variation point behaves as its default and cannot be set yet. */")
            appendLine("    val variationPointPlanned: Boolean get() = variationPoint.status == VpStatus.PLANNED")
            appendLine()
            appendLine("    /** Same value, ignoring the prose (INV-Q-3283: text-only edits create no version). */")
            appendLine("    fun sameValueAs(other: ProfileValue): Boolean = comparable() == other.comparable()")
            appendLine()
            appendLine("    private fun comparable() = copy(text = \"\", unresolved = unresolved?.let { UnresolvedValue(\"\", \"\") })")
            appendLine("}")
            appendLine()
            appendLine("/** How one variation point's value changed between two profile versions. */")
            appendLine("enum class ProfileChangeKind {")
            ProfileChangeKind.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/** One per-profile difference (INV-REQ-1245 b4). */")
            appendLine("data class ProfileValueChange(")
            appendLine("    val variationPoint: VariationPoint,")
            appendLine("    val kind: ProfileChangeKind,")
            appendLine("    val before: ProfileValue?,")
            appendLine("    val after: ProfileValue?,")
            appendLine(")")
            appendLine()
            appendLine("/**")
            appendLine(" * Every operating profile (INV-NOTE-3 §37.4, INV-REQ-1245): a versioned, named set of")
            appendLine(" * values (INV-Q-3283). Read by certification-kit, tenancy-svc and console-bff.")
            appendLine(" */")
            appendLine("enum class OperatingProfile(")
            appendLine("    val id: String,")
            appendLine("    val requirement: String,")
            appendLine("    val profileName: String,")
            appendLine("    val title: String,")
            appendLine("    val version: Int,")
            appendLine("    val status: ProfileStatus,")
            appendLine("    val note: String?,")
            appendLine("    val values: List<ProfileValue>,")
            appendLine("    /** The version in the previous vendored snapshot; null when there is none. */")
            appendLine("    val previousVersion: Int?,")
            appendLine("    val previousValues: List<ProfileValue>?,")
            appendLine(") {")
            profiles.forEach { p -> appendLine("    ${entry(p, prev?.get(p.id))},") }
            appendLine("    ;")
            appendLine()
            appendLine("    /** The value this profile sets for [vp], or null when it keeps the catalogue default. */")
            appendLine("    fun valueFor(vp: VariationPoint): ProfileValue? = values.find { it.variationPoint == vp }")
            appendLine()
            appendLine("    /** The planned variation points this profile sets (INV-REQ-1251). */")
            appendLine("    val plannedVariationPoints: List<VariationPoint> get() = values.filter { it.variationPointPlanned }.map { it.variationPoint }")
            appendLine()
            appendLine("    /** Values Keel has not typed yet, each naming its open question; the profile cannot be applied in full. */")
            appendLine("    val unresolvedValues: List<ProfileValue> get() = values.filter { it.unresolved != null }")
            appendLine()
            appendLine("    /** The difference from the previous snapshot's values (INV-REQ-1245 b4); empty when there is none. */")
            appendLine("    val changesFromPrevious: List<ProfileValueChange>")
            appendLine("        get() = previousValues?.let { OperatingProfiles.differences(it, values) } ?: emptyList()")
            appendLine()
            appendLine("    companion object {")
            appendLine("        fun fromId(id: String): OperatingProfile? = entries.find { it.id == id }")
            appendLine("    }")
            appendLine("}")
            appendLine()
            appendLine("/** Operations over profile values (INV-REQ-1245). */")
            appendLine("object OperatingProfiles {")
            appendLine("    /**")
            appendLine("     * What changes, per variation point, from [before] (e.g. the values of the version a")
            appendLine("     * tenant applied) to [after]: shown when a new version is offered, never applied silently.")
            appendLine("     */")
            appendLine("    fun differences(")
            appendLine("        before: List<ProfileValue>,")
            appendLine("        after: List<ProfileValue>,")
            appendLine("    ): List<ProfileValueChange> {")
            appendLine("        val b = before.associateBy { it.variationPoint }")
            appendLine("        val a = after.associateBy { it.variationPoint }")
            appendLine("        return (b.keys + a.keys).sortedBy { it.ordinal }.mapNotNull { vp ->")
            appendLine("            val old = b[vp]")
            appendLine("            val new = a[vp]")
            appendLine("            when {")
            appendLine("                old == null -> ProfileValueChange(vp, ProfileChangeKind.ADDED, null, new)")
            appendLine("                new == null -> ProfileValueChange(vp, ProfileChangeKind.REMOVED, old, null)")
            appendLine("                !old.sameValueAs(new) -> ProfileValueChange(vp, ProfileChangeKind.CHANGED, old, new)")
            appendLine("                else -> null")
            appendLine("            }")
            appendLine("        }")
            appendLine("    }")
            appendLine("}")
        }

    private fun entry(
        p: ParsedOperatingProfile,
        prev: ParsedOperatingProfile?,
    ): String =
        p.id.replace("-", "_") + "(" +
            listOf(
                p.id.lit(),
                p.requirement.lit(),
                p.name.lit(),
                p.title.lit(),
                p.version.toString(),
                "ProfileStatus.${p.status}",
                p.note?.lit() ?: "null",
                valuesLiteral(p.values),
                prev?.version?.toString() ?: "null",
                prev?.let { valuesLiteral(it.values) } ?: "null",
            ).joinToString(", ") + ")"

    private fun valuesLiteral(values: List<ParsedProfileValue>): String =
        if (values.isEmpty()) "emptyList()" else "listOf(" + values.joinToString(", ") { valueLiteral(it) } + ")"

    private fun valueLiteral(v: ParsedProfileValue): String {
        val args = mutableListOf("VariationPoint.${v.vp.replace("-", "_")}", v.requirement.lit(), v.text.lit())
        v.option?.let { args += "option = ${it.lit()}" }
        if (v.options.isNotEmpty()) args += "options = ${v.options.lit()}"
        v.typedValue?.let { args += "typedValue = ${typedLiteral(it)}" }
        v.condition?.let { args += "condition = ${it.lit()}" }
        if (v.recommended) args += "recommended = true"
        v.otherwiseOption?.let { args += "otherwiseOption = ${it.lit()}" }
        if (v.alternatives.isNotEmpty()) args += "alternatives = ${v.alternatives.lit()}"
        v.alternativeBy?.let { args += "alternativeBy = ${it.lit()}" }
        if (v.adds.isNotEmpty()) args += "adds = ${v.adds.lit()}"
        v.atApply?.let { args += "atApply = ${it.lit()}" }
        if (v.explicitDefault) args += "explicitDefault = true"
        if (v.needsAcknowledgement.isNotEmpty()) args += "needsAcknowledgement = ${v.needsAcknowledgement.lit()}"
        v.unresolved?.let { args += "unresolved = UnresolvedValue(${it.reason.lit()}, ${it.pendingQuestion.lit()})" }
        return "ProfileValue(" + args.joinToString(", ") + ")"
    }

    private fun typedLiteral(t: ProfileTypedValue): String {
        val value = t.value?.let { "java.math.BigDecimal(\"${it.toPlainString()}\")" } ?: "null"
        val fields =
            if (t.fields.isEmpty()) "" else ", mapOf(" + t.fields.entries.joinToString(", ") { (k, f) -> "${k.lit()} to ${typedLiteral(f)}" } + ")"
        return "ProfileTypedValue(ValueType.${t.type}, ${t.unit?.lit() ?: "null"}, $value$fields)"
    }

    private fun List<String>.lit(): String = "listOf(" + joinToString(", ") { it.lit() } + ")"

    private fun String.lit(): String =
        "\"" + replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n").replace("$", "\\$") + "\""
}
