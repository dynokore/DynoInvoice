package gst.catalogue

/**
 * Emits `ErrorCode.kt`: the generated half of the `gst-catalogue` artefact (STK-61,
 * CS-13). One `ErrorCode` enum entry per row, named `<AREA>_<NNN>` (a hand-typed code
 * string is a defect, FR-O.6/CS-13 — callers write `ErrorCode.ING_001`, never
 * `"ING-001"`). `Severity` and `Disposition` are generated here too, so the enum and
 * its two closed vocabularies come from the same source and can never drift apart.
 *
 * This file's own output is never hand-edited (its header says so) and is excluded
 * from detekt/ktlint in `gst-catalogue/build.gradle.kts`, matching the
 * `gst.contract-server` precedent in platform-build (generated code is not
 * hand-style-reviewed).
 */
object KotlinEmitter {
    fun emit(
        packageName: String,
        rows: List<ParsedErrorCode>,
        sourceCommit: String,
    ): String =
        buildString {
            appendLine("// GENERATED — do not edit by hand.")
            appendLine("//")
            appendLine("// Generated by catalogue/generator (INV-T-2851 / T7) from")
            appendLine("// catalogue/errors/error-codes.yaml, itself vendored from invoice-docs'")
            appendLine("// model/architecture/error-codes.yaml at commit $sourceCommit (STK-61, CS-13).")
            appendLine("// Re-run the generateErrorCodeCatalogue Gradle task after re-vendoring that file;")
            appendLine("// never edit this file directly.")
            appendLine()
            appendLine("package $packageName")
            appendLine()
            appendLine("/** INV-REQ-1178 (FR-O.1) behaviour #2: every error's severity is one of these four. */")
            appendLine("enum class Severity {")
            Severity.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine(
                "/** INV-REQ-1178 (FR-O.1) behaviour #2: every error's disposition, where it carries one, " +
                    "is one of these five. */",
            )
            appendLine("enum class Disposition {")
            Disposition.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/**")
            appendLine(" * Every GST InvoiceNow error code (STK-61): a stable `AREA-NNN` code, its condition,")
            appendLine(" * severity, disposition and remediation owner (INV-REQ-1178). Error codes are a public")
            appendLine(" * contract — never renumbered or repurposed (INV-REQ-1183); the stability check of")
            appendLine(" * INV-AC-2170 enforces this across trains.")
            appendLine(" */")
            appendLine(
                "enum class ErrorCode(val code: String, val condition: String, val severity: Severity, " +
                    "val disposition: Disposition?, val owner: String) {",
            )
            rows.forEach { row -> appendLine("    ${entryLine(row)},") }
            appendLine("    ;")
            appendLine()
            appendLine("    companion object {")
            appendLine("        fun fromCode(code: String): ErrorCode? = entries.find { it.code == code }")
            appendLine("    }")
            appendLine("}")
        }

    private fun entryLine(row: ParsedErrorCode): String {
        val constantName = "${row.area}_${"%03d".format(row.number)}"
        val dispositionLiteral = row.disposition?.let { "Disposition.$it" } ?: "null"
        return "${constantName}(\"${row.code}\", ${row.conditionCore.kotlinStringLiteralBody()}, " +
            "Severity.${row.severity}, $dispositionLiteral, ${row.owner.kotlinStringLiteralBody()})"
    }

    /** The escaped body of a Kotlin string literal, quotes included. */
    private fun String.kotlinStringLiteralBody(): String {
        val escaped =
            this
                .replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\n", "\\n")
                .replace("$", "\\$")
        return "\"$escaped\""
    }
}
