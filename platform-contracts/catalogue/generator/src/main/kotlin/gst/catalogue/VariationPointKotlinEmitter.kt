package gst.catalogue

/**
 * Emits `VariationPoint.kt`: the generated half of the `gst-catalogue` VariationPoint
 * catalogue (STK-61, CS-28, INV-T-2852). One `VariationPoint` enum entry per row,
 * named after its own `VP-nn` id (`VP_01` .. `VP_78`) — CS-28's own examples
 * (`VariationPoint.VP_20`, `VariationPoint.VP_13`) already assume this constant shape.
 * `VpClass`, `VpClassModifier` and `VpStatus` are generated here too, from the same
 * source, so the enum and its vocabularies can never drift apart.
 *
 * A `PolicyReader` port that resolves a tenant's *value* for one of these variation
 * points (CS-28's `policies.resolve<E>(vp, scope, at)`) is a different service's
 * concern, built against this typed catalogue — not part of this generator, which
 * only publishes the catalogue itself (id, class, options, default, bounds, setting
 * roles, scopes, owner, status, form-dependence, INV-T-2852's own done-when).
 */
object VariationPointKotlinEmitter {
    fun emit(
        packageName: String,
        rows: List<ParsedVariationPoint>,
    ): String =
        buildString {
            appendLine("// GENERATED — do not edit by hand.")
            appendLine("//")
            appendLine("// Generated by catalogue/generator (INV-T-2852 / T8) from")
            appendLine("// catalogue/variation-points/variation-points.yaml, itself vendored from the Keel")
            appendLine("// INV variation-point requirements (STK-61, CS-28) — see that file's own header.")
            appendLine("// Re-run the generateVariationPointCatalogue Gradle task after re-vendoring that")
            appendLine("// file; never edit this file directly.")
            appendLine()
            appendLine("package $packageName")
            appendLine()
            appendLine("/** INV-REQ-1239 (FR-AI.1) behaviour #1's fixed class vocabulary (`LAW` excluded: never a tenant option). */")
            appendLine("enum class VpClass {")
            VpClass.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/** A modifier on [VpClass] (INV-REQ-780 behaviour #1; INV-AC-1786). */")
            appendLine("enum class VpClassModifier {")
            VpClassModifier.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            appendLine("/** INV-REQ-1251 (FR-AI.13) behaviour #1's fixed status vocabulary. */")
            appendLine("enum class VpStatus {")
            VpStatus.entries.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
            emitFieldTypes()
            appendLine("/**")
            appendLine(" * Every GST InvoiceNow variation point (STK-61): its class, options, default (or")
            appendLine(" * must-be-elected), bounds, setting role, scope levels, owning service, status and")
            appendLine(" * the requirements it governs (INV-REQ-1239). One tenant's behaviour differs from")
            appendLine(" * another's only through the value of a variation point (behaviour #2); a value")
            appendLine(" * outside [options]/[bounds], or set by anyone other than [setBy], is refused")
            appendLine(" * (behaviour #3). Only [VpStatus.AVAILABLE] offers every option; [VpStatus.PLANNED]")
            appendLine(" * behaves as [default] until scenarios cover the options; [VpStatus.RETIRED] is")
            appendLine(" * never offered (INV-REQ-1251).")
            appendLine(" *")
            appendLine(" * [scopeLevels], [optionSpecs], [multiSelect] and [exclusiveKeys] are Keel's")
            appendLine(" * machine-readable catalogue fields (INV-T-3000; INV-Q-2934, INV-Q-2936): null/empty")
            appendLine(" * only on a retired row or while [pendingQuestions] names the open question.")
            appendLine(" */")
            appendLine("enum class VariationPoint(")
            appendLine("    val id: String,")
            appendLine("    val requirement: String,")
            appendLine("    val title: String,")
            appendLine("    val vpClass: VpClass,")
            appendLine("    val classModifiers: List<VpClassModifier>,")
            appendLine("    val scope: List<String>,")
            appendLine("    val owner: String,")
            appendLine("    val setBy: List<String>,")
            appendLine("    val mustBeElected: Boolean,")
            appendLine("    val default: String?,")
            appendLine("    val options: List<String>,")
            appendLine("    val bounds: String?,")
            appendLine("    val status: VpStatus,")
            appendLine("    val statusNote: String?,")
            appendLine("    val governs: List<String>,")
            appendLine("    val formDependence: String?,")
            appendLine("    val scopeLevels: List<ScopeLevel>?,")
            appendLine("    val optionSpecs: List<VpOption>?,")
            appendLine("    val multiSelect: Boolean,")
            appendLine("    val exclusiveKeys: List<String>,")
            appendLine("    val crossScope: String?,")
            appendLine("    val crossOption: String?,")
            appendLine("    val crossRow: String?,")
            appendLine("    val defaultByForm: Map<String, String>,")
            appendLine("    val installationParameter: TypedValue?,")
            appendLine("    val installationParameterRef: InstallationParameterRef?,")
            appendLine("    val secondApprover: String?,")
            appendLine("    val pendingQuestions: List<String>,")
            appendLine(") {")
            rows.forEach { row -> appendLine("    ${entryLine(row)},") }
            appendLine("    ;")
            appendLine()
            appendLine("    companion object {")
            appendLine("        fun fromId(id: String): VariationPoint? = entries.find { it.id == id }")
            appendLine("    }")
            appendLine("}")
            appendLine()
            appendLine("/** Typed access to the catalogue fields (TPL-10, INV-T-3000). */")
            appendLine("object Catalogue {")
            appendLine("    /**")
            appendLine("     * The option keys of [id] in catalogue order: the owning service's enum constants")
            appendLine("     * (TPL-10). Fails for an unknown id, and for a row whose keys Keel does not carry")
            appendLine("     * yet (naming the open question) — never a guessed key.")
            appendLine("     */")
            appendLine("    fun optionKeys(id: String): List<String> = optionKeys(requireNotNull(VariationPoint.fromId(id)) { \"unknown variation point \$id\" })")
            appendLine()
            appendLine("    fun optionKeys(vp: VariationPoint): List<String> {")
            appendLine("        val specs =")
            appendLine("            checkNotNull(vp.optionSpecs) {")
            appendLine("                if (vp.pendingQuestions.isEmpty()) {")
            appendLine("                    \"\${vp.id} has no option keys (status \${vp.status})\"")
            appendLine("                } else {")
            appendLine("                    \"\${vp.id}'s option keys are pending \${vp.pendingQuestions.joinToString()}\"")
            appendLine("                }")
            appendLine("            }")
            appendLine("        return specs.map { it.key }")
            appendLine("    }")
            appendLine("}")
        }

    private fun StringBuilder.emitFieldTypes() {
        fun enumBlock(
            doc: String,
            name: String,
            values: List<String>,
        ) {
            appendLine("/** $doc */")
            appendLine("enum class $name {")
            values.forEach { appendLine("    $it,") }
            appendLine("}")
            appendLine()
        }
        enumBlock("INV-REQ-1242 behaviour #1's scope levels.", "ScopeLevel", ScopeLevel.entries.map { it.name })
        enumBlock(
            "An option's strictness against the catalogue default (INV-Q-2936); LOOSER needs acknowledgeControlRelaxation (INV-REQ-1244).",
            "Strictness",
            Strictness.entries.map { it.name },
        )
        enumBlock("Which way a typed value tightens (INV-Q-2934).", "Direction", Direction.entries.map { it.name })
        enumBlock("The kind of a typed value (INV-Q-2934).", "ValueType", ValueType.entries.map { it.name })
        appendLine("/**")
        appendLine(" * A bound or default: a number, a named value resolved elsewhere, or [row], the id of the variation point")
        appendLine(" * whose value in force is the bound (INV-Q-3202). Exactly one is set.")
        appendLine(" */")
        appendLine("data class BoundValue(")
        appendLine("    val number: java.math.BigDecimal? = null,")
        appendLine("    val symbolic: String? = null,")
        appendLine("    val row: String? = null,")
        appendLine(")")
        appendLine()
        appendLine("/** An installation parameter made its own variation point [row] (requirement [requirement]; INV-Q-3202); its typed values are that row's. */")
        appendLine("data class InstallationParameterRef(")
        appendLine("    val row: String,")
        appendLine("    val requirement: String,")
        appendLine("    val name: String? = null,")
        appendLine("    val note: String? = null,")
        appendLine("    val rule: String? = null,")
        appendLine(")")
        appendLine()
        appendLine("/** A typed value with its bounds (INV-Q-2934); what Keel does not state stays null. */")
        appendLine("data class TypedValue(")
        appendLine("    val type: ValueType,")
        appendLine("    val name: String? = null,")
        appendLine("    val unit: String? = null,")
        appendLine("    val min: BoundValue? = null,")
        appendLine("    val max: BoundValue? = null,")
        appendLine("    val default: BoundValue? = null,")
        appendLine("    val direction: Direction? = null,")
        appendLine("    val ref: String? = null,")
        appendLine("    val filter: String? = null,")
        appendLine("    val ordered: Boolean? = null,")
        appendLine("    val requires: String? = null,")
        appendLine("    val fields: Map<String, TypedValue> = emptyMap(),")
        appendLine("    val minExclusive: BoundValue? = null,")
        appendLine("    val item: TypedValue? = null,")
        appendLine("    val key: TypedValue? = null,")
        appendLine("    val value: TypedValue? = null,")
        appendLine("    val values: List<String> = emptyList(),")
        appendLine("    val distinct: Boolean? = null,")
        appendLine("    val minItems: Int? = null,")
        appendLine("    val maxItems: Int? = null,")
        appendLine("    val length: BoundValue? = null,")
        appendLine("    val rule: String? = null,")
        appendLine("    val comparedWith: String? = null,")
        appendLine(")")
        appendLine()
        enumBlock("When a looser option's acknowledger is required (INV-REQ-1244 b2, INV-Q-3134).", "AckCondition", AckCondition.entries.map { it.name })
        enumBlock("The deployment forms a role set can differ by (INV-REQ-1248).", "DeploymentForm", DeploymentForm.entries.map { it.name })
        appendLine("/**")
        appendLine(" * One acknowledger of a LOOSER option (INV-T-3148): [roles] required under [condition]; [rolesByForm] names the")
        appendLine(" * roles per deployment form where they differ (then [roles] is empty); [distinctFromSetter] bars the setter.")
        appendLine(" */")
        appendLine("data class Acknowledger(")
        appendLine("    val roles: List<String>,")
        appendLine("    val condition: AckCondition,")
        appendLine("    val distinctFromSetter: Boolean,")
        appendLine("    val rolesByForm: Map<DeploymentForm, List<String>> = emptyMap(),")
        appendLine(")")
        appendLine()
        appendLine("/** One option at its catalogue position: [key] is the owning enum's constant (TPL-10). */")
        appendLine("data class VpOption(")
        appendLine("    val key: String,")
        appendLine("    val label: String,")
        appendLine("    val strictness: Strictness,")
        appendLine("    val typedValue: TypedValue? = null,")
        appendLine("    val acknowledgedBy: List<Acknowledger> = emptyList(),")
        appendLine(")")
        appendLine()
    }

    private fun optionSpecsLiteral(row: ParsedVariationPoint): String {
        val specs = row.fields?.options ?: return "null"
        return "listOf(" +
            specs.withIndex().joinToString(", ") { (i, o) ->
                "VpOption(${o.key.kotlinStringLiteralBody()}, ${row.options.getOrElse(i) { o.key }.kotlinStringLiteralBody()}, " +
                    "Strictness.${o.strictness}, ${o.typedValue?.let { typedLiteral(it) } ?: "null"}, " +
                    "${ackListLiteral(o.acknowledgedBy)})"
            } + ")"
    }

    private fun ackListLiteral(list: List<Acknowledger>): String =
        if (list.isEmpty()) {
            "emptyList()"
        } else {
            "listOf(" +
                list.joinToString(", ") { a ->
                    "Acknowledger(${a.roles.kotlinListLiteral()}, AckCondition.${a.condition}, ${a.distinctFromSetter}, " +
                        (
                            if (a.rolesByForm.isEmpty()) {
                                "emptyMap()"
                            } else {
                                "mapOf(" + a.rolesByForm.entries.joinToString(", ") { (k, r) -> "DeploymentForm.$k to ${r.kotlinListLiteral()}" } + ")"
                            }
                        ) + ")"
                } + ")"
        }

    private fun typedLiteral(t: TypedValue): String {
        val args = mutableListOf("ValueType.${t.type}")
        t.name?.let { args += "name = ${it.kotlinStringLiteralBody()}" }
        t.unit?.let { args += "unit = ${it.kotlinStringLiteralBody()}" }
        t.min?.let { args += "min = ${boundLiteral(it)}" }
        t.max?.let { args += "max = ${boundLiteral(it)}" }
        t.default?.let { args += "default = ${boundLiteral(it)}" }
        t.direction?.let { args += "direction = Direction.$it" }
        t.ref?.let { args += "ref = ${it.kotlinStringLiteralBody()}" }
        t.filter?.let { args += "filter = ${it.kotlinStringLiteralBody()}" }
        t.ordered?.let { args += "ordered = $it" }
        t.requires?.let { args += "requires = ${it.kotlinStringLiteralBody()}" }
        if (t.fields.isNotEmpty()) {
            args += "fields = mapOf(" +
                t.fields.entries.joinToString(", ") { (k, v) -> "${k.kotlinStringLiteralBody()} to ${typedLiteral(v)}" } + ")"
        }
        t.minExclusive?.let { args += "minExclusive = ${boundLiteral(it)}" }
        t.item?.let { args += "item = ${typedLiteral(it)}" }
        t.key?.let { args += "key = ${typedLiteral(it)}" }
        t.value?.let { args += "value = ${typedLiteral(it)}" }
        if (t.values.isNotEmpty()) args += "values = ${t.values.kotlinListLiteral()}"
        t.distinct?.let { args += "distinct = $it" }
        t.minItems?.let { args += "minItems = $it" }
        t.maxItems?.let { args += "maxItems = $it" }
        t.length?.let { args += "length = ${boundLiteral(it)}" }
        t.rule?.let { args += "rule = ${it.kotlinStringLiteralBody()}" }
        t.comparedWith?.let { args += "comparedWith = ${it.kotlinStringLiteralBody()}" }
        return "TypedValue(" + args.joinToString(", ") + ")"
    }

    private fun boundLiteral(b: BoundValue): String =
        b.number?.let { "BoundValue(number = java.math.BigDecimal(\"${it.toPlainString()}\"))" }
            ?: b.symbolic?.let { "BoundValue(symbolic = ${it.kotlinStringLiteralBody()})" }
            ?: "BoundValue(row = ${b.row!!.kotlinStringLiteralBody()})"

    private fun parameterRefLiteral(p: InstallationParameterRef): String =
        "InstallationParameterRef(${p.row.kotlinStringLiteralBody()}, ${p.requirement.kotlinStringLiteralBody()}, " +
            "${p.name.kotlinNullableStringLiteral()}, ${p.note.kotlinNullableStringLiteral()}, ${p.rule.kotlinNullableStringLiteral()})"

    private fun entryLine(row: ParsedVariationPoint): String {
        val constantName = row.id.replace("-", "_")
        val modifiersLiteral =
            if (row.classModifiers.isEmpty()) {
                "emptyList()"
            } else {
                "listOf(" + row.classModifiers.joinToString(", ") { "VpClassModifier.$it" } + ")"
            }
        return "$constantName(" +
            "${row.id.kotlinStringLiteralBody()}, " +
            "${row.requirement.kotlinStringLiteralBody()}, " +
            "${row.title.kotlinStringLiteralBody()}, " +
            "VpClass.${row.vpClass}, " +
            "$modifiersLiteral, " +
            "${row.scope.kotlinListLiteral()}, " +
            "${row.owner.kotlinStringLiteralBody()}, " +
            "${row.setBy.kotlinListLiteral()}, " +
            "${row.mustBeElected}, " +
            "${row.default.kotlinNullableStringLiteral()}, " +
            "${row.options.kotlinListLiteral()}, " +
            "${row.bounds.kotlinNullableStringLiteral()}, " +
            "VpStatus.${row.status}, " +
            "${row.statusNote.kotlinNullableStringLiteral()}, " +
            "${row.governs.kotlinListLiteral()}, " +
            "${row.formDependence.kotlinNullableStringLiteral()}, " +
            "${row.fields?.scopeLevels?.let { l -> "listOf(" + l.joinToString(", ") { "ScopeLevel.$it" } + ")" } ?: "null"}, " +
            "${optionSpecsLiteral(row)}, " +
            "${row.fields?.multiSelect ?: false}, " +
            "${(row.fields?.exclusiveKeys ?: emptyList()).kotlinListLiteral()}, " +
            "${row.fields?.crossScope.kotlinNullableStringLiteral()}, " +
            "${row.fields?.crossOption.kotlinNullableStringLiteral()}, " +
            "${row.fields?.crossRow.kotlinNullableStringLiteral()}, " +
            "${row.fields?.defaultByForm.orEmpty().let { m -> if (m.isEmpty()) "emptyMap()" else "mapOf(" + m.entries.joinToString(", ") { (k, v) -> "${k.kotlinStringLiteralBody()} to ${v.kotlinStringLiteralBody()}" } + ")" }}, " +
            "${row.fields?.installationParameter?.let { typedLiteral(it) } ?: "null"}, " +
            "${row.fields?.installationParameterRef?.let { parameterRefLiteral(it) } ?: "null"}, " +
            "${row.fields?.secondApprover.kotlinNullableStringLiteral()}, " +
            row.pendingQuestions.kotlinListLiteral() +
            ")"
    }

    private fun List<String>.kotlinListLiteral(): String =
        if (isEmpty()) "emptyList()" else "listOf(" + joinToString(", ") { it.kotlinStringLiteralBody() } + ")"

    private fun String?.kotlinNullableStringLiteral(): String = this?.kotlinStringLiteralBody() ?: "null"

    /** The escaped body of a Kotlin string literal, quotes included. */
    private fun String.kotlinStringLiteralBody(): String {
        val escaped =
            this
                .replace("\\", "\\\\")
                .replace("\"", "\\\"")
                .replace("\n", "\\n")
                .replace("$", "\\$")
        return "\"$escaped\""
    }
}
