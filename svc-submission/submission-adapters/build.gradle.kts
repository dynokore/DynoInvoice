// The clients of access-svc's `recordBreakGlassAction` (STK-46, ARC-08, INV-T-9348) and of transport-svc's
// `submitPayload` (INV-T-22121), generated by gst.contract-client (several contracts per module, platform-build
// 0.8.0 and later) from the pinned platform-contracts bundle (libs.versions.platformContractsBundle). The bundle is
// unpacked here, beside its `service-runtime/` directory that the contracts' `$ref` reaches, and is the source of
// the generator's prepare tasks: submission-contract stages only the submission contract. Each client is generated
// into `<clients package>.<service>.api` and `.model`.
contractClient {
    generatorSource("platform-contracts:access:openapi.yaml")
    generatorSource("platform-contracts:transport:openapi.yaml")
}

val contractsBundle by configurations.creating {
    isCanBeConsumed = false
    isCanBeResolved = true
    isTransitive = false
}
val unpackClientContracts =
    tasks.register<Sync>("unpackClientContracts") {
        from(zipTree(contractsBundle.singleFile)) {
            include("access/openapi.yaml", "transport/openapi.yaml", "service-runtime/**")
        }
        into(layout.buildDirectory.dir("client-contracts"))
    }
// The plugin resolves a coordinate against a repository; this module reads the unpacked bundle instead. The task
// without a suffix prepares the first contract (access) for the shared infrastructure task.
// (the per-service tasks are registered by the plugin in its own afterEvaluate, so this runs after it)
afterEvaluate {
    mapOf(
        "prepareContractClientSpec" to "access",
        "prepareContractClientSpecAccess" to "access",
        "prepareContractClientSpecTransport" to "transport",
    ).forEach { (task, service) ->
        tasks.named<gst.build.contracts.PrepareDecimalSpecTask>(task) {
            dependsOn(unpackClientContracts)
            source.set(layout.buildDirectory.file("client-contracts/$service/openapi.yaml"))
        }
    }
}

