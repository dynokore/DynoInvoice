// The client of access-svc's `recordBreakGlassAction` (STK-46, ARC-08, INV-T-9348), generated by gst.contract-client
// from the access contract of the pinned platform-contracts bundle (libs.versions.platformContractsBundle). The
// bundle is unpacked here, beside its `service-runtime/` directory that the contract's `$ref` reaches, and is the
// source of the generator's prepare task: submission-contract stages only the submission contract.
val accessBundle by configurations.creating {
    isCanBeConsumed = false
    isCanBeResolved = true
    isTransitive = false
}
val unpackAccessContract =
    tasks.register<Sync>("unpackAccessContract") {
        from(zipTree(accessBundle.singleFile)) {
            include("access/openapi.yaml", "service-runtime/**")
        }
        into(layout.buildDirectory.dir("access-contract"))
    }
tasks.named<gst.build.contracts.PrepareDecimalSpecTask>("prepareContractClientSpec") {
    dependsOn(unpackAccessContract)
    source.set(layout.buildDirectory.file("access-contract/access/openapi.yaml"))
}

